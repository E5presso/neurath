"""SQLAlchemy repository for scoped host-session observations."""

from typing import override

from sqlalchemy import select
from sqlalchemy.orm import Session
from sqlalchemy.orm.exc import StaleDataError

from neurath.application.ports.repositories.session import ISessionRepository
from neurath.domain.aggregates.session import HostSession
from neurath.domain.errors import ContextNotFound, RevisionConflict
from neurath.infrastructure.models.session import SessionModel


class SessionRepository(ISessionRepository):
    """Persist host observations using the ORM optimistic version mechanism."""

    def __init__(self, session: Session) -> None:
        """Bind one existing request transaction, never a cached connection.

        Args:
            session: Request-local SQLAlchemy session.
        """
        self.session = session

    @override
    def find(self, project_id: str, provider: str, host_session_id: str) -> HostSession | None:
        """Find a native identifier only inside its project and provider scope.

        Args:
            project_id: Stable identifier of the project to address.
            provider: Host provider namespace for the native session identifier.
            host_session_id: Native session identifier supplied by the host provider.

        Returns:
            HostSession | None: Matching session in the given project/provider scope, or None.
        """
        record = self.session.scalar(
            select(SessionModel).where(
                SessionModel.project_id == project_id,
                SessionModel.provider == provider,
                SessionModel.host_session_id == host_session_id,
            )
        )
        if record is None:
            return None
        return record.to_domain()

    @override
    def get(self, project_id: str, session_id: str) -> HostSession:
        """Reject session identifiers belonging to another project.

        Args:
            project_id: Stable identifier of the project to address.
            session_id: Identifier of the session within the addressed project.

        Returns:
            HostSession: Session belonging to the explicitly addressed project.
        """
        record = self._get_record(project_id, session_id)
        return record.to_domain()

    def _get_record(self, project_id: str, session_id: str) -> SessionModel:
        """Read a scoped ORM record within the current transaction.

        Args:
            project_id: Stable identifier of the project to address.
            session_id: Identifier of the session within the addressed project.

        Returns:
            SessionModel: Scoped ORM record for conversion to a detached entity.

        Raises:
            ContextNotFound: The addressed project or session does not exist in the requested scope.
        """
        record = self.session.scalar(
            select(SessionModel).where(
                SessionModel.project_id == project_id, SessionModel.id == session_id
            )
        )
        if record is None:
            raise ContextNotFound("Session does not exist in the requested project")
        return record

    @override
    def add(self, session: HostSession) -> None:
        """Stage and flush a new observation without taking ownership of commit.

        Args:
            session: Domain session entity to persist within the current transaction.
        """
        self.session.add(SessionModel.from_domain(session))
        self.session.flush()

    @override
    def save(self, session: HostSession) -> HostSession:
        """Merge a detached entity using SQLAlchemy's optimistic version check.

        SQLAlchemy compares the supplied version before copying state and again
        during UPDATE. Unchanged state follows the ORM's normal dirty checking.

        Args:
            session: Entity with the version originally observed by its caller.

        Returns:
            HostSession: Persisted session with the version generated by SQLAlchemy.

        Raises:
            RevisionConflict: Another writer changed the stored version.
        """
        try:
            record = self.session.merge(SessionModel.from_domain(session))
            self.session.flush()
        except StaleDataError as error:
            raise RevisionConflict(
                "Session changed; read current context before updating"
            ) from error
        return record.to_domain()
